-- Matches the JPA entities in src/main/java/com/pgmanagement/entity (spring.jpa.hibernate.ddl-auto=validate).

CREATE TABLE app_users (
    id             NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name           VARCHAR2(100) NOT NULL,
    email          VARCHAR2(150) NOT NULL,
    phone          VARCHAR2(20)  NOT NULL,
    password_hash  VARCHAR2(100) NOT NULL,
    role           VARCHAR2(20)  NOT NULL,
    gender         VARCHAR2(10),
    created_at     TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('OWNER', 'CUSTOMER', 'SUPPORT')),
    CONSTRAINT ck_users_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER'))
);

CREATE TABLE pgs (
    id                 NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    owner_id           NUMBER(19)     NOT NULL,
    name               VARCHAR2(150)  NOT NULL,
    description        VARCHAR2(2000),
    address_line       VARCHAR2(300)  NOT NULL,
    area               VARCHAR2(100)  NOT NULL,
    city               VARCHAR2(100)  NOT NULL,
    state              VARCHAR2(100)  NOT NULL,
    pincode            VARCHAR2(10)   NOT NULL,
    latitude           FLOAT(53)    ,
    longitude          FLOAT(53)    ,
    gender_preference  VARCHAR2(10)   DEFAULT 'ANY' NOT NULL,
    facilities         VARCHAR2(1000),
    contact_phone      VARCHAR2(20)   NOT NULL,
    house_rules        VARCHAR2(2000),
    registered_via     VARCHAR2(20)   DEFAULT 'OWNER' NOT NULL,
    active             NUMBER(1)      DEFAULT 1 NOT NULL,
    created_at         TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_pgs_owner FOREIGN KEY (owner_id) REFERENCES app_users (id),
    CONSTRAINT ck_pgs_gender CHECK (gender_preference IN ('MALE', 'FEMALE', 'ANY')),
    CONSTRAINT ck_pgs_via CHECK (registered_via IN ('OWNER', 'CUSTOMER_CARE')),
    CONSTRAINT ck_pgs_active CHECK (active IN (0, 1))
);
CREATE INDEX ix_pgs_owner ON pgs (owner_id);
CREATE INDEX ix_pgs_city_area ON pgs (city, area);
CREATE INDEX ix_pgs_geo ON pgs (latitude, longitude);

CREATE TABLE pg_media (
    id          NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    pg_id       NUMBER(19)     NOT NULL,
    media_type  VARCHAR2(10)   NOT NULL,
    url         VARCHAR2(1000) NOT NULL,
    sort_order  NUMBER(10)     NOT NULL,
    CONSTRAINT fk_media_pg FOREIGN KEY (pg_id) REFERENCES pgs (id) ON DELETE CASCADE,
    CONSTRAINT ck_media_type CHECK (media_type IN ('IMAGE', 'VIDEO'))
);
CREATE INDEX ix_media_pg ON pg_media (pg_id);

CREATE TABLE rooms (
    id                 NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    pg_id              NUMBER(19)    NOT NULL,
    floor_number       NUMBER(10)    NOT NULL,
    room_number        VARCHAR2(20)  NOT NULL,
    sharing_type       NUMBER(10)    NOT NULL,
    ac                 NUMBER(1)     NOT NULL,
    attached_bathroom  NUMBER(1)     NOT NULL,
    daily_rent         NUMBER(10, 2) NOT NULL,
    weekly_rent        NUMBER(10, 2) NOT NULL,
    monthly_rent       NUMBER(10, 2) NOT NULL,
    CONSTRAINT fk_rooms_pg FOREIGN KEY (pg_id) REFERENCES pgs (id) ON DELETE CASCADE,
    CONSTRAINT uk_rooms_pg_number UNIQUE (pg_id, room_number),
    CONSTRAINT ck_rooms_sharing CHECK (sharing_type BETWEEN 1 AND 10),
    CONSTRAINT ck_rooms_ac CHECK (ac IN (0, 1)),
    CONSTRAINT ck_rooms_bath CHECK (attached_bathroom IN (0, 1))
);

CREATE TABLE beds (
    id         NUMBER(19)   GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    room_id    NUMBER(19)   NOT NULL,
    bed_label  VARCHAR2(10) NOT NULL,
    status     VARCHAR2(20) DEFAULT 'AVAILABLE' NOT NULL,
    version    NUMBER(19),
    CONSTRAINT fk_beds_room FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
    CONSTRAINT uk_beds_room_label UNIQUE (room_id, bed_label),
    CONSTRAINT ck_beds_status CHECK (status IN ('AVAILABLE', 'BLOCKED', 'BOOKED', 'UNAVAILABLE'))
);
CREATE INDEX ix_beds_status ON beds (status);

CREATE TABLE bookings (
    id             NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    customer_id    NUMBER(19)     NOT NULL,
    pg_id          NUMBER(19)     NOT NULL,
    bed_id         NUMBER(19)     NOT NULL,
    booking_type   VARCHAR2(10)   NOT NULL,
    payment_plan   VARCHAR2(10)   DEFAULT 'FULL' NOT NULL,
    duration       NUMBER(10)     NOT NULL,
    start_date     DATE           NOT NULL,
    end_date       DATE           NOT NULL,
    total_amount   NUMBER(12, 2)  NOT NULL,
    status         VARCHAR2(20)   DEFAULT 'REQUESTED' NOT NULL,
    customer_note  VARCHAR2(1000),
    owner_note     VARCHAR2(1000),
    created_at     TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_bookings_customer FOREIGN KEY (customer_id) REFERENCES app_users (id),
    CONSTRAINT fk_bookings_pg FOREIGN KEY (pg_id) REFERENCES pgs (id),
    CONSTRAINT fk_bookings_bed FOREIGN KEY (bed_id) REFERENCES beds (id),
    CONSTRAINT ck_bookings_type CHECK (booking_type IN ('DAILY', 'WEEKLY', 'MONTHLY', 'YEARLY')),
    CONSTRAINT ck_bookings_plan CHECK (payment_plan IN ('FULL', 'MONTHLY')),
    CONSTRAINT ck_bookings_status CHECK (status IN ('REQUESTED', 'APPROVED', 'REJECTED', 'BOOKED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT ck_bookings_dates CHECK (end_date >= start_date)
);
CREATE INDEX ix_bookings_customer ON bookings (customer_id);
CREATE INDEX ix_bookings_pg_status ON bookings (pg_id, status);
CREATE INDEX ix_bookings_bed ON bookings (bed_id);

CREATE TABLE payments (
    id               NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    booking_id       NUMBER(19)    NOT NULL,
    installment_no   NUMBER(10)    NOT NULL,
    amount           NUMBER(12, 2) NOT NULL,
    due_date         DATE          NOT NULL,
    period_start     DATE          NOT NULL,
    period_end       DATE          NOT NULL,
    status           VARCHAR2(20)  DEFAULT 'DUE' NOT NULL,
    payment_method   VARCHAR2(30),
    transaction_ref  VARCHAR2(100),
    owner_note       VARCHAR2(500),
    submitted_at     TIMESTAMP(6),
    paid_at          TIMESTAMP(6),
    invoice_number   VARCHAR2(40),
    CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id) REFERENCES bookings (id) ON DELETE CASCADE,
    CONSTRAINT uk_payments_invoice UNIQUE (invoice_number),
    CONSTRAINT uk_payments_installment UNIQUE (booking_id, installment_no),
    CONSTRAINT ck_payments_status CHECK (status IN ('DUE', 'SUBMITTED', 'PAID'))
);
CREATE INDEX ix_payments_status_due ON payments (status, due_date);

CREATE TABLE notifications (
    id          NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id     NUMBER(19)     NOT NULL,
    title       VARCHAR2(200)  NOT NULL,
    message     VARCHAR2(2000) NOT NULL,
    link        VARCHAR2(200),
    is_read     NUMBER(1)      DEFAULT 0 NOT NULL,
    created_at  TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE,
    CONSTRAINT ck_notifications_read CHECK (is_read IN (0, 1))
);
CREATE INDEX ix_notifications_user ON notifications (user_id, is_read);

CREATE TABLE support_requests (
    id            NUMBER(19)     GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name          VARCHAR2(100)  NOT NULL,
    phone         VARCHAR2(20)   NOT NULL,
    email         VARCHAR2(150),
    request_type  VARCHAR2(20)   NOT NULL,
    message       VARCHAR2(2000),
    status        VARCHAR2(20)   DEFAULT 'OPEN' NOT NULL,
    created_at    TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_support_type CHECK (request_type IN ('CALLBACK', 'REGISTER_PG', 'GENERAL')),
    CONSTRAINT ck_support_status CHECK (status IN ('OPEN', 'RESOLVED'))
);
CREATE INDEX ix_support_status ON support_requests (status);
