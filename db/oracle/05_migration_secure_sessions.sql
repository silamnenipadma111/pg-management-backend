-- Upgrade an existing database to the secure sign-in release:
-- email verification flag, server-side sessions (HttpOnly cookie) and single-use email tokens.
-- Existing accounts stay verified (DEFAULT 1), so nobody is locked out by the upgrade.
ALTER TABLE app_users ADD (email_verified NUMBER(1) DEFAULT 1 NOT NULL);
ALTER TABLE app_users ADD CONSTRAINT ck_users_verified CHECK (email_verified IN (0, 1));

CREATE TABLE user_sessions (
    id            NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id       NUMBER(19)    NOT NULL,
    token_hash    VARCHAR2(64)  NOT NULL,
    csrf_token    VARCHAR2(64)  NOT NULL,
    created_at    TIMESTAMP(6)  NOT NULL,
    last_used_at  TIMESTAMP(6)  NOT NULL,
    expires_at    TIMESTAMP(6)  NOT NULL,
    revoked_at    TIMESTAMP(6),
    ip_address    VARCHAR2(45),
    user_agent    VARCHAR2(255),
    CONSTRAINT fk_sessions_user FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE,
    CONSTRAINT uk_sessions_token UNIQUE (token_hash)
);
CREATE INDEX ix_sessions_user ON user_sessions (user_id);
CREATE INDEX ix_sessions_expires ON user_sessions (expires_at);

CREATE TABLE auth_tokens (
    id          NUMBER(19)    GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    user_id     NUMBER(19)    NOT NULL,
    purpose     VARCHAR2(30)  NOT NULL,
    token_hash  VARCHAR2(64)  NOT NULL,
    created_at  TIMESTAMP(6)  NOT NULL,
    expires_at  TIMESTAMP(6)  NOT NULL,
    used_at     TIMESTAMP(6),
    CONSTRAINT fk_auth_tokens_user FOREIGN KEY (user_id) REFERENCES app_users (id) ON DELETE CASCADE,
    CONSTRAINT uk_auth_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_auth_tokens_purpose CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET'))
);
CREATE INDEX ix_auth_tokens_user ON auth_tokens (user_id, purpose);

